import { chromium } from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:1365,height:900}});
const errors=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("console",msg=>{if(msg.type()==="error")console.log("BROWSER CONSOLE ERROR:",msg.text())});
page.on("requestfailed",r=>console.log("FAILED REQUEST",r.url(),r.failure()?.errorText));
const base=process.env.ATLAS_BASE||"http://127.0.0.1:8765";
try{
  await page.goto(base,{waitUntil:"domcontentloaded",timeout:45000});
  await page.waitForTimeout(4500);
  console.log("INIT DEBUG",JSON.stringify({badge:await page.locator("#dataBadge").textContent(),errors,heading:await page.title(),statCount:await page.locator("#heroStats .stat strong").count()}));
  await page.waitForFunction(()=>document.querySelector("#dataBadge")?.textContent?.includes("verified data series"),null,{timeout:16000});
  await page.waitForFunction(()=>document.querySelectorAll("#heroStats .stat strong").length>=4,{timeout:40000});
  const stats=await page.locator("#heroStats .stat strong").allTextContents();
  if(stats.every(v=>v.includes("No data")))throw Error("Headline values all unavailable");
  console.log("Home stats",stats);
  if(!stats[0].startsWith("₹"))throw Error("GVA headline must show monetary units, got "+stats[0]);
  await page.locator('[data-page="map"]').click();
  await page.waitForFunction(()=>Number(document.querySelector("#indiaMap")?.dataset?.renderedStates)>=25 && Number(document.querySelector("#indiaMap")?.dataset?.coloredStates)>=5 && document.querySelector("#mapLeaders .leader-row"),null,{timeout:70000});
  const shapes=await page.locator("#indiaMap svg path").count();
  if(shapes<25)throw Error("Only "+shapes+" India map states drawn");
  await page.locator("#indiaMap svg path").first().click({force:true});
  await page.waitForFunction(()=>!document.querySelector("#stateClickPanel")?.classList.contains("hidden"),null,{timeout:15000});
  const mapDetail=await page.evaluate(async()=>{
    const geo=await (await fetch("data/india-states.geojson")).json();
    const polygons=geo.features.flatMap(f=>f.geometry.type==="Polygon"?[f.geometry.coordinates]:f.geometry.coordinates);
    const numVertices=polygons.flatMap(p=>p.flat()).length;
    const all=polygons.flatMap(p=>p.flat());
    return{features:geo.features.length,vertices:numVertices,longitude:[Math.min(...all.map(p=>p[0])),Math.max(...all.map(p=>p[0]))],latitude:[Math.min(...all.map(p=>p[1])),Math.max(...all.map(p=>p[1]))]};
  });
  if(mapDetail.features!==36||mapDetail.vertices<10000||mapDetail.longitude[0]>69||mapDetail.longitude[1]<96||mapDetail.latitude[0]>8||mapDetail.latitude[1]<35)throw Error("Invalid or oversimplified India state geometry: "+JSON.stringify(mapDetail));
  console.log("Geographic fidelity checks",mapDetail);
  console.log("Clickable India SVG states",shapes);
  await page.locator("#indiaMap").screenshot({path:"india-map-screenshot.png"});
  const leaders=await page.locator("#mapLeaders .leader-row").count();
  if(leaders<5)throw Error("Insufficient map leaders: "+leaders);
  console.log("Map leaders",leaders);
  await page.locator('[data-page="states"]').click();
  await page.waitForFunction(()=>document.querySelectorAll("#stateProfile .profile-card strong").length===4,{timeout:40000});
  const cards=await page.locator("#stateProfile .profile-card strong").allTextContents();
  if(cards.every(x=>x==="No data"))throw Error("State profile all missing");
  console.log("State profile",cards);
  await page.locator('[data-page="industries"]').click();
  await page.waitForFunction(()=>document.querySelectorAll("#industryProfile .profile-card strong").length===4,{timeout:70000});
  console.log("Industry profile",await page.locator("#industryProfile .profile-card strong").allTextContents());
  await page.locator('[data-page="rankings"]').click();
  await page.waitForFunction(()=>document.querySelector("#rankingChart .main-svg"),{timeout:45000});
  await page.locator('[data-page="insights"]').click();
  await page.waitForFunction(()=>document.querySelectorAll("#allInsights .insight-card").length>1,{timeout:45000});
  console.log("Insights",await page.locator("#allInsights .insight-card").count());
  await page.locator('[data-page="compare"]').click();
  await page.waitForFunction(()=>document.querySelector("#compareChart .main-svg"),{timeout:45000});
  await page.locator("#addLine").click();
  if(await page.locator(".compare-row").count()<3)throw Error("Add comparison did not work");
  console.log("Comparison rows",await page.locator(".compare-row").count());

  await page.locator('[data-page="visuals"]').click();
  await page.waitForFunction(()=>document.querySelector("#visualChart .main-svg"),null,{timeout:45000});
  console.log("Visual quadrant rendered");
  await page.locator('[data-visual="treemap"]').click();
  await page.waitForFunction(()=>document.querySelector("#visualChart .treemaplayer"),null,{timeout:45000});
  console.log("Treemap rendered");
  await page.locator('[data-visual="heatmap"]').click();
  await page.waitForFunction(()=>document.querySelector("#visualChart .heatmaplayer"),null,{timeout:45000});
  console.log("Heatmap rendered");
  await page.locator('[data-visual="rankshift"]').click();
  await page.waitForFunction(()=>document.querySelector("#visualChart .scatterlayer"),null,{timeout:45000});
  console.log("Ranking shift rendered");
  if(errors.length)throw Error("Runtime errors: "+errors.join(" | "));
  console.log("ALL INTERACTIVE SMOKE TESTS PASSED");
}finally{
  await page.screenshot({path:"smoke-screenshot.png",fullPage:true}).catch(()=>{});
  await browser.close();
}
